<?php
/**
 * One-time web installer.
 * Creates the database tables, the first admin account and app/config.php.
 * Refuses to run again once app/config.php exists. Delete this file after installing.
 */
define('ST_INSTALLER', true);
require __DIR__ . '/app/bootstrap.php';

$installed = is_file(ST_APP . '/config.php');
$errors = [];
$done = false;
$checks = [
    'PHP 7.4 or newer' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO extension' => class_exists('PDO'),
    'PDO MySQL driver' => class_exists('PDO') && in_array('mysql', PDO::getAvailableDrivers(), true),
    'JSON extension' => function_exists('json_encode'),
    'mbstring extension' => function_exists('mb_substr'),
    'app/ folder writable (to save config.php)' => is_writable(ST_APP),
    'uploads/ folder writable' => is_writable(ST_ROOT . '/uploads'),
    'storage/ folder writable' => is_writable(ST_ROOT . '/storage'),
    'GD or Imagick with WebP (optional — converts & compresses every uploaded image to WebP)' => Media::engine() !== '',
];
$sqliteAvailable = class_exists('PDO') && in_array('sqlite', PDO::getAvailableDrivers(), true);

$v = [
    'driver' => $_POST['driver'] ?? 'mysql',
    'host' => $_POST['host'] ?? 'localhost',
    'port' => $_POST['port'] ?? '3306',
    'name' => $_POST['name'] ?? '',
    'user' => $_POST['user'] ?? '',
    'pass' => $_POST['pass'] ?? '',
    'prefix' => $_POST['prefix'] ?? 'st_',
    'admin_user' => $_POST['admin_user'] ?? 'admin',
    'admin_email' => $_POST['admin_email'] ?? '',
    'admin_name' => $_POST['admin_name'] ?? '',
    'notify_email' => $_POST['notify_email'] ?? '',
];

if (!$installed && is_post()) {
    $pass1 = (string)($_POST['admin_pass'] ?? '');
    $pass2 = (string)($_POST['admin_pass2'] ?? '');
    if (!preg_match('/^[A-Za-z0-9_.@-]{3,64}$/', $v['admin_user'])) $errors[] = 'Username: 3–64 letters, numbers, dot, dash, underscore or @.';
    if (strlen($pass1) < 10) $errors[] = 'Admin password must be at least 10 characters.';
    if ($pass1 !== $pass2) $errors[] = 'The two passwords do not match.';
    if ($v['admin_email'] !== '' && !filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Admin e-mail is not valid.';
    if (!preg_match('/^[A-Za-z0-9_]{0,20}$/', $v['prefix'])) $errors[] = 'Table prefix may only contain letters, numbers and underscores.';
    if ($v['driver'] === 'mysql' && $v['name'] === '') $errors[] = 'Enter the database name.';
    if (!is_writable(ST_APP)) $errors[] = 'The app/ folder is not writable, so config.php cannot be saved. Set its permission to 755 in cPanel File Manager.';

    if (!$errors) {
        if ($v['driver'] === 'sqlite') {
            $db = ['driver' => 'sqlite', 'path' => ST_ROOT . '/storage/site.sqlite', 'prefix' => $v['prefix']];
        } else {
            $db = ['driver' => 'mysql', 'host' => $v['host'], 'port' => (int)$v['port'], 'name' => $v['name'],
                'user' => $v['user'], 'pass' => $v['pass'], 'prefix' => $v['prefix']];
        }
        try {
            DB::connect($db);
            DB::migrate();
            if (DB::value('SELECT COUNT(*) FROM {users} WHERE username = ?', [$v['admin_user']])) {
                DB::update('users', ['password_hash' => password_hash($pass1, PASSWORD_DEFAULT)], 'username = ?', [$v['admin_user']]);
            } else {
                DB::insert('users', [
                    'username' => $v['admin_user'],
                    'email' => $v['admin_email'],
                    'name' => $v['admin_name'],
                    'password_hash' => password_hash($pass1, PASSWORD_DEFAULT),
                    'role' => 'admin',
                    'created_at' => now(),
                ]);
            }
            if ($v['notify_email'] !== '') {
                Settings::set('notify_email', $v['notify_email']);
            }
            $config = [
                'db' => $db,
                'app_key' => random_token(32),
                'timezone' => 'Asia/Kolkata',
                'debug' => false,
                // 'site_url' => 'https://www.example.com',   // optional: fixed origin for sitemap / share links
            ];
            $php = "<?php\n// Generated by install.php on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn "
                . var_export($config, true) . ";\n";
            $php = str_replace("'" . addslashes(ST_ROOT), "ST_ROOT . '", $php);
            if (file_put_contents(ST_APP . '/config.php', $php, LOCK_EX) === false) {
                throw new RuntimeException('Could not write app/config.php');
            }
            @chmod(ST_APP . '/config.php', 0640);
            $done = true;
            $installed = true;
        } catch (Throwable $e) {
            $errors[] = 'Database error: ' . $e->getMessage();
        }
    }
}
